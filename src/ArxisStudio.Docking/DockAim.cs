namespace ArxisStudio.Docking;

/// <summary>
/// Куда просится брошенная вкладка.
/// </summary>
/// <remarks>
/// Разбор случаев, а не пара «группа и сторона»: у броска четыре разных смысла,
/// и три из них парой не выразить — ни место в полосе вкладок, ни полосу во всё
/// окно, ни отдельное окно. Пока намерение было парой, вкладка умела вставать
/// только в конец полосы, а корневой стыковки не существовало вовсе.
/// <para>
/// Намерение считает вид — он один знает, где что лежит на экране, — а
/// применяет его <see cref="DockTree.Apply"/>. Через ту же функцию строится и
/// предпросмотр, поэтому показанное человеку и полученное им — буквально один
/// и тот же результат.
/// </para>
/// </remarks>
public abstract record DockAim
{
    /// <summary>
    /// Вкладкой в группу, на указанное место в полосе.
    /// </summary>
    /// <param name="Group">Имя группы.</param>
    /// <param name="At">Место в полосе; вне диапазона — в конец.</param>
    public sealed record Tab(string Group, int At) : DockAim;

    /// <summary>
    /// Разделить группу и встать с этой стороны.
    /// </summary>
    /// <param name="Group">Имя группы.</param>
    /// <param name="Side">С какой стороны от неё.</param>
    public sealed record Split(string Group, DockSide Side) : DockAim;

    /// <summary>
    /// Полосой во всё дерево окна, с этой стороны.
    /// </summary>
    /// <param name="Side">С какой стороны от всего дерева.</param>
    /// <remarks>
    /// Отличается от <see cref="Split"/> тем, кого заворачивают: полоса
    /// становится соседом всего дерева разом, а не чьей-то колонки. Иначе
    /// консоль во всю ширину окна собрать нечем — любое деление оказывается
    /// внутри соседа.
    /// </remarks>
    public sealed record Frame(DockSide Side) : DockAim;

    /// <summary>
    /// Отдельным окном.
    /// </summary>
    /// <remarks>
    /// Середина области значит именно это. Так человеку не нужен свободный
    /// рабочий стол, чтобы оторвать панель, и каждый жест получает ровно один
    /// смысл: вкладкой — в полосу, разделить — к краю, оторвать — в середину.
    /// </remarks>
    public sealed record Float : DockAim;
}
