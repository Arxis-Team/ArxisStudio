namespace ArxisStudio.Shell.Localization;

/// <summary>
/// Откуда берётся строка по ключу.
/// </summary>
/// <remarks>
/// Источник не один: у студии свои словари, у каждого плагина — свои. Общего
/// словаря на всех быть не может, потому что ключ вроде <c>panel.main</c>
/// придумают двое, и словарь достался бы тому, кто загрузился первым.
/// <para>
/// Слежением за языком источники не занимаются: строки, показанные на экране,
/// обновляет <see cref="Localizer"/> — один список на студию, куда попадают и
/// строки плагинов.
/// </para>
/// </remarks>
public interface IStringSource
{
    /// <summary>Строка по ключу; ненайденная возвращается как <c>!ключ!</c>.</summary>
    /// <param name="key">Ключ строки.</param>
    string this[string key] { get; }
}
