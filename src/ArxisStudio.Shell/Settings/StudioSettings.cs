using System.Text.Json.Serialization;

namespace ArxisStudio.Shell.Settings;

/// <summary>Вариант оформления студии.</summary>
public enum StudioTheme
{
    /// <summary>Тёмная тема.</summary>
    Dark,

    /// <summary>Светлая тема.</summary>
    Light,
}

/// <summary>Плотность интерфейса: шаг строки и расстояния между вещами.</summary>
/// <remarks>
/// Порядок объявления — порядок на экране, от плотной к просторной. Значение
/// по умолчанию задаёт не порядок, а инициализатор свойства: файл, записанный
/// студией, которая плотности ещё не знала, поля не содержит, и такой файл
/// обязан читаться как обычная ступень, а не как первая по списку.
/// </remarks>
public enum StudioDensity
{
    /// <summary>Плотная: строка 20, контрол 24, расстояния на ступень меньше.</summary>
    Compact,

    /// <summary>Обычная: значения темы как они есть.</summary>
    Normal,

    /// <summary>Просторная: строка 28, контрол 32, расстояния на ступень больше.</summary>
    Comfortable,
}

/// <summary>
/// Настройки студии: то, что переживает перезапуск и правится в окне настроек.
/// Простая изменяемая модель — её сериализует <see cref="JsonSettingsStore"/>.
/// </summary>
/// <remarks>
/// Здесь только то, за чем стоит читатель. Акцентный цвет и плотность
/// интерфейса лежали в модели и в файле с первого дня, но не значили ничего:
/// цвет и отступы приходят из темы, а настройка, которую можно поправить и не
/// увидеть разницы, — обещание, которого никто не давал.
/// <para>
/// Плотность вернулась вместе с тем, кто её читает. Стать настройкой ей мешали
/// сотни чисел в разметке: ступень, переопределяющая токены, которых никто не
/// зовёт, не делает ничего. Когда отступы переехали в токены, у неё появилось,
/// что двигать. Акцентный цвет по-прежнему ждёт своего читателя.
/// </para>
/// </remarks>
public sealed class StudioSettings
{
    /// <summary>Оформление.</summary>
    public StudioTheme Theme { get; set; } = StudioTheme.Dark;

    /// <summary>Плотность интерфейса.</summary>
    /// <remarks>
    /// В файле поле называется <c>interfaceDensity</c>, а не <c>density</c>, и это
    /// не вкус. <c>density</c> в файле уже есть — у всех, кто запускал студию до
    /// того, как поле сняли с модели: оно записывалось с первого дня и не значило
    /// ничего. Прочитай студия его сейчас, выбор, сделанный, когда он ничего не
    /// менял, ожил бы после обновления и молча сжал бы интерфейс. Так и случилось
    /// на первой же живой проверке. Прежний ключ читатель пропускает, а первая
    /// запись его уже не повторит.
    /// </remarks>
    [JsonPropertyName("interfaceDensity")]
    public StudioDensity Density { get; set; } = StudioDensity.Normal;

    /// <summary>
    /// Язык интерфейса: код культуры, например <c>en</c> или <c>ru</c>.
    /// </summary>
    /// <remarks>
    /// При первом запуске — английский: это язык, на котором написана студия,
    /// и на него же падает всё непереведённое. Выбранный однажды язык лежит
    /// здесь и переживает обновления.
    /// </remarks>
    public string Language { get; set; } = Localization.Localizer.FallbackLanguage;
}
