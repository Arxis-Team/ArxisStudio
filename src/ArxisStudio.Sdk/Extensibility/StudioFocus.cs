namespace ArxisStudio.Sdk;

/// <summary>
/// Каретка клавиатуры в панелях студии.
/// </summary>
/// <remarks>
/// Служба отдельная от <see cref="IStudioToolWindows"/>, и различие несущее:
/// <c>Show</c> показывает, <c>Focus</c> переносит каретку. Показать просит и
/// проснувшийся плагин — из <c>Activate</c> на запуске студии, — и каретка,
/// выдернутая им из редактора, это потерянное нажатие. Фокусировать просят
/// там, где человек уже сказал, чего хочет: нажал кнопку панели, выбрал пункт
/// меню, закончил действие, ради которого панель и открывали.
/// <para>
/// Имя панели — из манифеста, без имени плагина: обёртка подставляет хозяина
/// сама, и чужие панели отсюда недостижимы по построению.
/// </para>
/// </remarks>
public interface IStudioFocus
{
    /// <summary>
    /// Показывает панель и отдаёт ей каретку.
    /// </summary>
    /// <param name="toolWindowId">Идентификатор панели из манифеста — без имени плагина.</param>
    /// <returns>Досталась ли каретка кому-нибудь внутри панели.</returns>
    /// <remarks>
    /// Ответ <c>false</c> значит, что внутри панели некому её взять: ни одного
    /// контрола, который умеет фокус. Это не ошибка студии и не повод бросать —
    /// это ответ о том, что панелью нельзя управлять с клавиатуры.
    /// </remarks>
    bool Focus(string toolWindowId);

    /// <summary>Каретка сейчас внутри этой панели.</summary>
    /// <param name="toolWindowId">Идентификатор панели из манифеста — без имени плагина.</param>
    bool IsFocused(string toolWindowId);
}
