namespace ArxisStudio.Sdk;

/// <summary>
/// Состояние своих элементов в полосе студии: плагин говорит — студия помнит и
/// показывает.
/// </summary>
/// <remarks>
/// Достаётся через <see cref="IStudioContext.GetService{T}"/>. Модель здесь —
/// сообщение, а не опрос: студия ничего не спрашивает у плагина, чтобы нарисовать
/// его кнопку, и потому кнопка стоит на месте и у спящего плагина, и у только что
/// выгруженного. Состояние живёт у студии; плагин лишь меняет его, когда у него
/// есть повод — запустил, остановил, включил режим.
/// <para>
/// Чужие элементы отсюда недостижимы по построению: служба выдаётся каждому
/// плагину своя и знает, чья она. Элемент, которого нет в манифесте этого
/// плагина, — замечание в журнал, а не исключение: полоса не то место, из-за
/// которого стоит падать.
/// </para>
/// <para>
/// Звать можно из любого потока — из фоновой задачи в том числе: студия сама
/// перенесёт изменение в поток интерфейса.
/// </para>
/// </remarks>
public interface IStudioToolBar
{
    /// <summary>
    /// Меняет состояние своего элемента; пропущенный флаг остаётся как был.
    /// </summary>
    /// <param name="itemId">Идентификатор элемента из манифеста — без имени плагина.</param>
    /// <param name="isEnabled">Доступен ли элемент; выключенный виден, но не отвечает.</param>
    /// <param name="isVisible">Показан ли элемент; скрытый места не занимает.</param>
    /// <param name="isChecked">
    /// Включён ли инструмент — только у кнопки: так кнопка становится
    /// переключателем.
    /// </param>
    void Update(string itemId, bool? isEnabled = null, bool? isVisible = null, bool? isChecked = null);
}
