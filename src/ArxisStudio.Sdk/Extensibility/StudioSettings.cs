namespace ArxisStudio.Sdk;

/// <summary>
/// Настройки плагина: то, что о нём помнит студия между запусками.
/// </summary>
/// <remarks>
/// Ключи объявляются в манифесте, и это не формальность: по объявлению студия
/// знает, в какой области хранить значение, какого оно типа и как показать его
/// человеку в экране настроек. Ключ, которого в манифесте нет, студия не примет
/// — иначе значение легло бы неизвестно куда и не показалось бы никому, включая
/// того, кто его записал.
/// <para>
/// Здесь хранят то, что правит человек. Приватную память плагина — последнюю
/// открытую вкладку, кэш, размер панели — в настройки класть не следует: их
/// увидят в общем списке, и человек будет гадать, что это и можно ли это
/// трогать.
/// </para>
/// </remarks>
public interface IStudioSettings
{
    /// <summary>
    /// Читает значение настройки.
    /// </summary>
    /// <typeparam name="T">Тип значения: строка, логическое или число.</typeparam>
    /// <param name="key">Ключ, объявленный в манифесте.</param>
    /// <returns>
    /// Значение из проектной области, если оно там есть, иначе из
    /// пользовательской, иначе объявленное в манифесте значение по умолчанию.
    /// </returns>
    T? Get<T>(string key);

    /// <summary>
    /// Записывает значение настройки.
    /// </summary>
    /// <param name="key">Ключ, объявленный в манифесте.</param>
    /// <param name="value">Новое значение; null стирает записанное.</param>
    /// <remarks>
    /// Куда лечь, решает объявленная область: у настройки, объявленной
    /// проектной, значение уедет вместе с проектом, у пользовательской —
    /// останется на этой машине. Спрашивать об этом плагин студия не будет:
    /// область — свойство настройки, а не отдельного её изменения.
    /// </remarks>
    void Set(string key, object? value);

    /// <summary>
    /// Настройку изменили; аргумент — её ключ.
    /// </summary>
    /// <remarks>
    /// Изменить её могут не только из плагина: человек правит настройки в
    /// студии и руками в файле. Плагин, которому важно значение, читает его по
    /// этому событию заново, а не запоминает при запуске.
    /// </remarks>
    event EventHandler<string>? Changed;
}
