using Avalonia.Data;

namespace ArxisStudio.Sdk;

/// <summary>
/// Строки плагина на языке студии.
/// </summary>
/// <remarks>
/// Словари лежат в папке плагина: <c>lang/strings.json</c> — язык, на котором
/// плагин написан, <c>lang/strings.&lt;код&gt;.json</c> — переводы. Студия
/// читает их сама, не загружая сборки: заголовок панели и пункт меню видны в
/// списке раньше, чем плагин впервые поднимут, и взять текст из его кода тогда
/// неоткуда.
/// <para>
/// Словари у каждого плагина свои, и чужих ключей — ни студии, ни соседа — в
/// них не видно. Иначе ключ вроде <c>panel.main</c>, придуманный дважды,
/// доставался бы тому, кого раньше загрузили, а переименование строки внутри
/// студии молча меняло бы текст в чужой панели.
/// </para>
/// </remarks>
public interface IStudioStrings
{
    /// <summary>
    /// Строка по ключу.
    /// </summary>
    /// <param name="key">Ключ в словарях плагина.</param>
    /// <returns>
    /// Текст на языке студии; если перевода нет — из словаря по умолчанию;
    /// если нет и там — <c>!ключ!</c>, чтобы пропуск был виден и не
    /// притворялся текстом.
    /// </returns>
    string this[string key] { get; }

    /// <summary>Код языка, на котором сейчас говорит студия.</summary>
    string Language { get; }

    /// <summary>
    /// Привязка к строке, переживающая смену языка.
    /// </summary>
    /// <param name="key">Ключ в словарях плагина.</param>
    /// <returns>Привязка для <c>Bind</c>.</returns>
    /// <remarks>
    /// Индексатор возвращает текст на сейчас, и подпись, поставленная им,
    /// останется на прежнем языке до перезагрузки панели. Привязка обновляется
    /// сама — тем же способом, каким это делает интерфейс самой студии.
    /// </remarks>
    BindingBase Text(string key);
}
