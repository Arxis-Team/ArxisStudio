namespace ArxisStudio.Sdk;

/// <summary>
/// Ход работы: то, что человек видит, пока задача идёт.
/// </summary>
/// <remarks>
/// Доля известна не всегда: у обхода дерева файлов её можно посчитать, у
/// запроса в сеть — нет. Задача, не сообщившая доли, показывается неопределённой
/// — это честнее выдуманного процента, по которому человек станет прикидывать
/// время.
/// </remarks>
public interface IStudioProgress
{
    /// <summary>Говорит, чем задача занята сейчас.</summary>
    /// <param name="message">Короткая строка вида «качаю кадры, 42 из 120».</param>
    void Report(string message);

    /// <summary>Сообщает долю сделанного.</summary>
    /// <param name="fraction">Доля от 0 до 1; за пределами — обрезается.</param>
    /// <param name="message">Чем занята сейчас; null — оставить прежнее.</param>
    void Report(double fraction, string? message = null);
}

/// <summary>
/// Фоновые задачи плагина.
/// </summary>
/// <remarks>
/// Весь код плагина студия зовёт из потока интерфейса: команда из меню, кнопка
/// на панели, активация. Долгое дело, сделанное там же, замораживает всю студию
/// — окно перестаёт перерисовываться, и через несколько секунд система
/// подписывает его «не отвечает». Всё, что заметно дольше мгновения — сеть,
/// обход файлов, запуск процесса, разбор сотен файлов, — идёт сюда.
/// <para>
/// Имя задачи и её ход студия показывает сама, в одном месте на всех: своей
/// мельницы плагину заводить не нужно. Отмена тоже общая — человек нажимает
/// крестик, и в работу приходит отмена токеном.
/// </para>
/// <para>
/// Вызванная из потока интерфейса, <c>await</c> вернёт вас в него же: обновлять
/// свою панель после задачи можно прямо в продолжении. Внутри самой работы
/// трогать интерфейс нельзя — она идёт в потоке из пула.
/// </para>
/// </remarks>
public interface IStudioTasks
{
    /// <summary>
    /// Выполняет работу в фоне, показывая её ход.
    /// </summary>
    /// <typeparam name="T">Что работа возвращает.</typeparam>
    /// <param name="title">Имя задачи для человека: «Импорт макета».</param>
    /// <param name="work">Сама работа.</param>
    /// <returns>Результат работы.</returns>
    /// <remarks>
    /// Отмена — не сбой: отменённая задача возвращает
    /// <see cref="OperationCanceledException"/>, и ловить её, чтобы записать в
    /// журнал как ошибку, не нужно. Всё остальное, чем работа кончилась плохо,
    /// студия припишет плагину и покажет человеку.
    /// </remarks>
    Task<T> RunAsync<T>(string title, Func<IStudioProgress, CancellationToken, Task<T>> work);

    /// <summary>Выполняет работу в фоне, не ожидая от неё результата.</summary>
    /// <param name="title">Имя задачи для человека.</param>
    /// <param name="work">Сама работа.</param>
    Task RunAsync(string title, Func<IStudioProgress, CancellationToken, Task> work);
}
