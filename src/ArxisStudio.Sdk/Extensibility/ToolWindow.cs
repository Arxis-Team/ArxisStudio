using Avalonia.Controls;

namespace ArxisStudio.Sdk;

/// <summary>
/// Панель плагина: студия ставит её содержимое в объявленную зону.
/// </summary>
/// <remarks>
/// Содержимое создаётся один раз и по требованию — панель, которую никто не
/// открыл, не должна строить свой интерфейс. Строить его следует на контролах
/// <c>Ax*</c>: панели плагина и панели студии стоят рядом, и разнобой видно
/// сразу.
/// </remarks>
public abstract class ToolWindow
{
    private Control? _content;

    /// <summary>Что студия даёт плагину; доступен после <see cref="Attach"/>.</summary>
    protected IStudioContext Context { get; private set; } = null!;

    /// <summary>Содержимое панели.</summary>
    public Control Content => _content ??= Build();

    /// <summary>Связывает панель со студией.</summary>
    /// <param name="context">Что студия даёт плагину.</param>
    public void Attach(IStudioContext context)
    {
        ArgumentNullException.ThrowIfNull(context);

        Context = context;
    }

    /// <summary>Строит интерфейс панели.</summary>
    /// <returns>Корневой контрол панели.</returns>
    protected abstract Control Build();

    /// <summary>
    /// Панель уходит: пора отпустить всё, что она держала.
    /// </summary>
    /// <remarks>
    /// Зовётся, когда расширение выключают, — перед тем как выгрузят его
    /// сборку, и на всякой дороге: перезагрузка, отключение за сбои, закрытие
    /// студии. Панель к этому времени уже снята с экрана.
    /// <para>
    /// Отпускать здесь надо то же, что и в <see cref="StudioPlugin.Deactivate"/>:
    /// подписки на события студии, таймеры, потоки, запущенные процессы. Точка
    /// нужна отдельная, потому что до всего этого дотягивается панель, а не
    /// точка входа: панели создаёт студия, и своих экземпляров расширение не
    /// видит. Прежде такому расширению приходилось заводить обходную дорогу от
    /// панели к точке входа — статикой, потому что другой у него не было.
    /// </para>
    /// <para>
    /// Не <see cref="IDisposable"/> нарочно: панель не отдают в <c>using</c> и
    /// не освобождают дважды: её зовёт студия и ровно один раз. Обещать при
    /// этом весь договор <c>Dispose</c> — с финализаторами и повторными
    /// вызовами — значит обещать больше, чем здесь происходит.
    /// </para>
    /// <para>
    /// Содержимое отпускать не нужно: контролы снимает студия. Упавшее здесь
    /// расширение никого за собой не унесёт — вызов идёт через тот же шов, что
    /// и остальные.
    /// </para>
    /// </remarks>
    public virtual void Release()
    {
    }
}
