namespace ArxisStudio.Sdk;

/// <summary>
/// Точка входа плагина: студия находит наследника в сборке плагина и поднимает
/// его при активации.
/// </summary>
/// <remarks>
/// Наследник обязан иметь конструктор без аргументов — студия создаёт его сама.
/// Всё, что плагину нужно от студии, приходит в <see cref="Activate"/>: держать
/// контекст в поле можно, пользоваться им после <see cref="Deactivate"/> — нет.
/// </remarks>
public abstract class StudioPlugin
{
    /// <summary>Плагин поднят: самое время заявить команды и панели.</summary>
    /// <param name="context">Что студия даёт плагину.</param>
    public virtual void Activate(IStudioContext context)
    {
    }

    /// <summary>
    /// Плагин выключают: пора отпустить всё, что он держал.
    /// </summary>
    /// <remarks>
    /// После этого сборку плагина выгружают, а выгрузка в .NET кооперативная:
    /// она закончится, только когда на типы плагина не останется ни одной
    /// ссылки. Держит их обычно не сам плагин, а студия — по его же просьбе:
    /// <list type="bullet">
    ///   <item>подписка на событие студии (<c>Changed</c> журнала, проблем,
    ///   выделения): делегат ссылается на метод плагина, а тот — на его
    ///   сборку;</item>
    ///   <item>таймер, задача или поток, которые он запустил и не остановил;</item>
    ///   <item>объект плагина, отданный студии и где-то ею сохранённый.</item>
    /// </list>
    /// Всё это надо отпустить здесь. Не отпущенное не приведёт к ошибке —
    /// приведёт к тому, что при перезагрузке в памяти окажутся две копии
    /// плагина, и прежняя продолжит получать события, на которые подписалась.
    /// Студия это заметит и скажет человеку, что надёжнее её перезапустить.
    /// </remarks>
    public virtual void Deactivate()
    {
    }
}

/// <summary>
/// Невизуальная часть плагина: служба, которая живёт, пока плагин включён.
/// </summary>
/// <remarks>
/// Плагин может быть только службой, только панелью или тем и другим сразу —
/// одно другого не требует.
/// </remarks>
public abstract class StudioService
{
    /// <summary>Служба запускается.</summary>
    /// <param name="context">Что студия даёт плагину.</param>
    public abstract void Start(IStudioContext context);

    /// <summary>
    /// Служба останавливается.
    /// </summary>
    /// <remarks>
    /// Здесь останавливают то, что служба завела: таймеры, задачи, потоки,
    /// наблюдение за файлами. Работающий поток из сборки плагина не даст её
    /// выгрузить — как и подписка, о которой сказано в
    /// <see cref="StudioPlugin.Deactivate"/>.
    /// </remarks>
    public virtual void Stop()
    {
    }
}
