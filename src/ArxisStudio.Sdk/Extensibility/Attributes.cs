namespace ArxisStudio.Sdk;

/// <summary>
/// Помечает панель плагина: студия покажет её в объявленной зоне.
/// </summary>
/// <remarks>
/// Идентификатор должен совпадать с объявленным в манифесте: манифест студия
/// читает, не загружая сборку, и по нему строит список панелей до того, как
/// атрибут вообще станет виден.
/// </remarks>
/// <param name="id">Идентификатор панели, как в манифесте.</param>
[AttributeUsage(AttributeTargets.Class, Inherited = false)]
public sealed class ToolWindowAttribute(string id) : Attribute
{
    /// <summary>Идентификатор панели.</summary>
    public string Id { get; } = id;
}

/// <summary>
/// Помечает свой контрол в полосе студии: элемент манифеста вида <c>custom</c>.
/// </summary>
/// <remarks>
/// Как и у панели, идентификатор должен совпадать с объявленным в манифесте:
/// место в полосе студия отводит по манифесту, не загружая сборку, а класс по
/// атрибуту находит уже потом, когда плагин поднят. Кнопки и меню атрибута не
/// требуют — их студия рисует сама.
/// </remarks>
/// <param name="id">Идентификатор элемента, как в манифесте.</param>
[AttributeUsage(AttributeTargets.Class, Inherited = false)]
public sealed class ToolBarItemAttribute(string id) : Attribute
{
    /// <summary>Идентификатор элемента.</summary>
    public string Id { get; } = id;
}

/// <summary>
/// Помечает код пункта создания: пункт манифеста вида <c>code</c>.
/// </summary>
/// <remarks>
/// Как и у панели, идентификатор должен совпадать с объявленным в манифесте: пункт в меню «Добавить ▸»
/// студия ставит по манифесту, не загружая сборку, а класс находит по атрибуту, когда расширение
/// поднято. Класс наследует <see cref="NewItemMaker"/>. Разойтись манифесту с кодом не даст сборка:
/// <c>ARX0016</c> называет пункт без класса, <c>ARX0017</c> — класс без пункта.
/// </remarks>
/// <param name="id">Идентификатор пункта, как в манифесте.</param>
[AttributeUsage(AttributeTargets.Class, Inherited = false)]
public sealed class NewItemAttribute(string id) : Attribute
{
    /// <summary>Идентификатор пункта.</summary>
    public string Id { get; } = id;
}

/// <summary>
/// Помечает метод обработчиком команды, объявленной в манифесте.
/// </summary>
/// <remarks>
/// Студия сама заявит его при подъёме плагина — звать
/// <see cref="IStudioCommands.Register"/> руками не нужно. Метод должен быть
/// без параметров. В точке входа и в службе он может быть и обычным, и
/// статическим: объект уже создан студией, и команда видит то же состояние,
/// что и остальной плагин. В любом другом открытом классе сборки — только
/// статическим, и сам класс тоже может быть статическим: создавать ради
/// команды объект, которому студия ничего не давала, она не станет.
/// <para>
/// Идентификатор тот же, что в манифесте: по манифесту студия строит меню, не
/// загружая сборку, а атрибут связывает объявленное с кодом. Команда, которой
/// нет в манифесте, работать будет, но в меню не появится — её некому туда
/// поставить.
/// </para>
/// </remarks>
/// <param name="id">Идентификатор команды, как в манифесте.</param>
[AttributeUsage(AttributeTargets.Method, Inherited = false)]
public sealed class CommandAttribute(string id) : Attribute
{
    /// <summary>Идентификатор команды.</summary>
    public string Id { get; } = id;
}
