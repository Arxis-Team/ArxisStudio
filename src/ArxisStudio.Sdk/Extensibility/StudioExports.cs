namespace ArxisStudio.Sdk;

/// <summary>
/// Обмен реализациями между плагинами: один публикует, сосед берёт.
/// </summary>
/// <remarks>
/// Достаётся через <see cref="IStudioContext.GetService{T}"/>. Тип, которым
/// обмениваются, обязан жить в контрактной сборке (<c>provides.contracts</c>
/// поставщика): только тогда он один на всех, и приведение у соседа не падает.
/// <para>
/// Публикуют в <c>Activate</c>, и снимать руками не нужно: студия снимает
/// публикации плагина при его выгрузке — так же, как снимает команды.
/// Потребитель поэтому не хранит взятое подолгу: сосед мог перезагрузиться,
/// и придержанный объект — это его прежняя, уже выгруженная копия. Взял,
/// использовал, отпустил; надолго — бери заново по событию
/// <see cref="IStudioPlugins.Changed"/>.
/// </para>
/// <para>
/// Сбой внутри взятой реализации прилетает берущему обычным исключением:
/// студия не встаёт между двумя плагинами. Необработанным его припишут
/// виновнику по стеку — как любое падение.
/// </para>
/// </remarks>
public interface IStudioExports
{
    /// <summary>
    /// Публикует реализацию от имени этого плагина.
    /// </summary>
    /// <typeparam name="T">Контрактный тип — интерфейс из контрактной сборки.</typeparam>
    /// <param name="implementation">Реализация.</param>
    /// <returns>
    /// <c>false</c>, если тип уже занят другим плагином: два поставщика на
    /// один тип — это не выбор, а гонка, и выиграл бы тот, кого раньше
    /// загрузили.
    /// </returns>
    bool Publish<T>(T implementation) where T : class;

    /// <summary>
    /// Берёт опубликованную реализацию.
    /// </summary>
    /// <typeparam name="T">Контрактный тип.</typeparam>
    /// <returns>Реализация или null, если никто не публиковал.</returns>
    T? Get<T>() where T : class;
}
