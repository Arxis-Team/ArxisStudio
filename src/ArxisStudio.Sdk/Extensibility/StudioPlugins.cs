namespace ArxisStudio.Sdk;

/// <summary>
/// Соседи глазами плагина: кто поднят и какой версии.
/// </summary>
/// <remarks>
/// Достаётся через <see cref="IStudioContext.GetService{T}"/> — новая служба,
/// а не новое свойство контекста: так список услуг растёт, не ломая уже
/// написанные реализации.
/// <para>
/// Служба нужна необязательным зависимостям. Обязательная зависимость в
/// вопросах не нуждается: раз плагин поднят, его обязательные соседи стоят под
/// ним. Необязательного соседа может не быть — и прежде чем показать кнопку
/// интеграции с ним, плагин спрашивает здесь.
/// </para>
/// </remarks>
public interface IStudioPlugins
{
    /// <summary>
    /// Поднят ли сосед и работает ли.
    /// </summary>
    /// <param name="pluginId">Идентификатор соседа.</param>
    /// <remarks>
    /// Сосед, объявленный в зависимостях с нижней границей версии и
    /// оказавшийся старее, считается отсутствующим — даже если технически
    /// поднят: спрашивающий написан под возможности, которых в старой версии
    /// нет, и «да» здесь означало бы падение на первом же обращении.
    /// </remarks>
    bool IsActive(string pluginId);

    /// <summary>
    /// Версия установленного соседа из его манифеста.
    /// </summary>
    /// <param name="pluginId">Идентификатор соседа.</param>
    /// <returns>Версия или null, если сосед не установлен.</returns>
    /// <remarks>
    /// Отвечает по манифесту, не загружая сборок: версия есть и у соседа,
    /// который ещё ждёт своего события, и у языкового пакета, которому
    /// подниматься нечем.
    /// </remarks>
    string? Version(string pluginId);

    /// <summary>
    /// Состав поднятых изменился: кто-то поднялся, выгрузился или перезагрузился.
    /// </summary>
    /// <remarks>
    /// Подписку снимают в <c>Deactivate</c>: забытая, она держит контекст
    /// плагина, и честная проверка выгрузки это покажет. Во время каскадов
    /// событие приходит на каждый шаг — подписчик может увидеть промежуточные
    /// состояния.
    /// </remarks>
    event EventHandler? Changed;
}
