using Avalonia.Controls;

namespace ArxisStudio.Sdk;

/// <summary>
/// Вклад расширения в контракт модуля: класс, который студия сама находит, строит, связывает с хозяином и
/// снимает при его выгрузке.
/// </summary>
/// <remarks>
/// Модуль, чей контракт расширяют, — инспектор с его редакторами свойств, — объявляет в контрактной сборке
/// абстрактного наследника этого класса, а расширение наследует его у себя открытым классом с открытым
/// конструктором без параметров. Собирает вклады модуль одним вызовом
/// <see cref="IStudioContributions.Collect{T}"/>: студия находит такие классы в сборках каждого поднятого
/// расширения, строит их через шов сбоев, отдаёт каждому контекст его хозяина и снимает, когда хозяина
/// выгружают. Так же студия всегда собирала свои вклады — редакторы документов и код пунктов создания.
/// <para>
/// Записи руками здесь нет нарочно: модуль не знает, кто его зовёт, — контекст не называет расширение, а
/// опубликованный экспорт у всех один, — и запись, сделанная плагином в реестре модуля, пережила бы его
/// выгрузку, держа его контекст загрузки, и звалась бы мимо шва. Появилось в SDK 7.19.
/// </para>
/// </remarks>
public abstract class StudioContribution
{
    /// <summary>Что студия дала хозяину вклада; доступен после <see cref="Attach"/>.</summary>
    /// <remarks>
    /// Контекст хозяина, а не того, кто собирает: вклад берёт отсюда свои строки, свои настройки и пишет в
    /// журнал от своего имени. Прежние рисовальщики свойств студии не видели вовсе и не могли взять даже
    /// своих строк.
    /// </remarks>
    protected IStudioContext Context { get; private set; } = null!;

    /// <summary>Связывает вклад со студией; следом зовётся <see cref="OnAttached"/>.</summary>
    /// <param name="context">Что студия даёт хозяину вклада.</param>
    public void Attach(IStudioContext context)
    {
        ArgumentNullException.ThrowIfNull(context);

        Context = context;
        OnAttached();
    }

    /// <summary>Вклад связан со студией: <see cref="Context"/> уже есть.</summary>
    /// <remarks>Зовётся через шов, как и конструктор: упавший вклад в набор не попадает.</remarks>
    protected virtual void OnAttached()
    {
    }

    /// <summary>Вклад уходит: пора отпустить всё, что он держал.</summary>
    /// <remarks>
    /// Зовётся, когда хозяина выгружают или когда собравший вклад модуль уходит сам, — прощальной дорогой
    /// шва: и у хозяина, отключённого за сбои. Отпускают здесь подписки на события студии и таймеры —
    /// то же, что панель отпускает в <see cref="ToolWindow.Release"/>.
    /// </remarks>
    public virtual void Release()
    {
    }
}

/// <summary>
/// Сбор вкладов в контракт модуля и вызовы чужого кода через шов сбоев студии.
/// </summary>
/// <remarks>
/// Берётся через <see cref="IStudioContext.GetService{T}"/>, и выдаётся каждому своя: собранное
/// записывается на собравшего и уходит вместе с ним. Нужна модулю, который даёт другим расширениям
/// дополнять себя классами, — так инспектор собирает редакторы свойств, разделы и метаданные, — и всякому,
/// кто зовёт объект, отданный ему чужим расширением. Появилось в SDK 7.19.
/// </remarks>
public interface IStudioContributions
{
    /// <summary>
    /// Вклады в контракт: экземпляры открытых неабстрактных наследников <typeparamref name="T"/> из сборок
    /// каждого поднятого расширения, и поднятого потом — тоже.
    /// </summary>
    /// <typeparam name="T">Тип вклада — класс из контрактной сборки модуля.</typeparam>
    /// <returns>Живой набор: поднятое расширение входит в него, выгруженное — уходит.</returns>
    /// <remarks>
    /// Первый вызов будит спящих, ждущих события <c>onContribution:</c> с идентификатором модуля, который
    /// объявил контракт <typeparamref name="T"/>, — раньше, чем набор соберётся: плагин, вся работа
    /// которого — вклад в чужой контракт, иначе не проснулся бы никогда. Повторный вызов отдаёт тот же
    /// набор.
    /// <para>
    /// Тип из сборки самого плагина, а не из контрактной, набором не станет: его не назвал бы никто,
    /// кроме собравшего, а записи держали бы его контекст загрузки. Студия скажет об этом в журнал и
    /// отдаст пустой набор.
    /// </para>
    /// </remarks>
    IStudioContributionSet<T> Collect<T>() where T : StudioContribution;

    /// <summary>
    /// Ручка к объекту, отданному чужим расширением: вызовы его кода — через шов, на счёт хозяина.
    /// </summary>
    /// <typeparam name="T">Тип объекта, каким его знает берущий.</typeparam>
    /// <param name="foreign">Объект.</param>
    /// <returns>Ручка; хозяин — расширение, загрузившее сборку, где объявлен класс объекта.</returns>
    /// <remarks>
    /// Так модуль держит то, что ему вручили: цель инспектора, показанную плагином, или поле, построенное
    /// его редактором. Ручка отпускает объект, когда хозяина выгружают, и говорит об этом событием
    /// <see cref="IStudioGuarded{T}.Released"/> — раньше выгрузки. Объект студии и общих сборок своего
    /// хозяина не имеет: его код ручка зовёт напрямую.
    /// </remarks>
    IStudioGuarded<T> Guard<T>(T foreign) where T : class;
}

/// <summary>Живой набор вкладов одного типа.</summary>
/// <typeparam name="T">Тип вклада.</typeparam>
public interface IStudioContributionSet<out T> where T : StudioContribution
{
    /// <summary>
    /// Вклады — снимок: модули раньше плагинов, расширения в порядке подъёма, классы — в порядке сборки.
    /// </summary>
    IReadOnlyList<IStudioContribution<T>> Items { get; }

    /// <summary>Состав набора сменился: расширение поднялось или ушло.</summary>
    /// <remarks>Приходит в потоке интерфейса, после того как ушедшие вклады отпущены.</remarks>
    event EventHandler? Changed;
}

/// <summary>
/// Ручка к чужому объекту: зовёт его код через шов сбоев студии и отпускает его с выгрузкой хозяина.
/// </summary>
/// <typeparam name="T">Тип объекта.</typeparam>
/// <remarks>
/// Шов приписывает падение хозяину, считает падения подряд и после третьего перестаёт звать расширение —
/// как у панелей и редакторов документов: сломанный плагин не роняет ни студию, ни модуль, который его
/// позвал. Сам объект ручка наружу не отдаёт — держать его дольше вызова и значило бы пережить его хозяина.
/// </remarks>
public interface IStudioGuarded<out T> where T : class
{
    /// <summary>Идентификатор хозяина; пусто — объект студии, у которого хозяина нет.</summary>
    string OwnerId { get; }

    /// <summary>Объект отпущен: хозяина выгрузили, и звать больше некого.</summary>
    bool IsReleased { get; }

    /// <summary>Объект отпускают — до выгрузки хозяина, в потоке интерфейса.</summary>
    /// <remarks>Отсюда снимают с экрана то, что объект построил: оставшись, оно держало бы его контекст.</remarks>
    event EventHandler? Released;

    /// <summary>Зовёт код объекта.</summary>
    /// <param name="what">Что просили сделать — попадёт в журнал, если упадёт.</param>
    /// <param name="call">Сам вызов.</param>
    /// <returns><c>true</c>, если вызов прошёл; <c>false</c> — упал, хозяин отключён или объект отпущен.</returns>
    bool Run(string what, Action<T> call);

    /// <summary>Зовёт код объекта за ответом.</summary>
    /// <typeparam name="TResult">Что объект должен вернуть.</typeparam>
    /// <param name="what">Что просили сделать.</param>
    /// <param name="call">Сам вызов.</param>
    /// <param name="result">Ответ; умолчание, если вызов не прошёл.</param>
    /// <returns><c>true</c>, если вызов прошёл.</returns>
    bool TryGet<TResult>(string what, Func<T, TResult> call, out TResult? result);

    /// <summary>Зовёт асинхронный код объекта и ждёт его.</summary>
    /// <param name="what">Что просили сделать.</param>
    /// <param name="call">Сам вызов.</param>
    /// <returns><c>true</c>, если вызов прошёл; ловится и падение до первого <c>await</c>, и после.</returns>
    Task<bool> RunAsync(string what, Func<T, Task> call);

    /// <summary>Зовёт прощальный код объекта — и у хозяина, которого звать перестали за сбои.</summary>
    /// <param name="what">С чем прощаются.</param>
    /// <param name="call">Сам вызов.</param>
    /// <returns><c>true</c>, если прощание прошло; упавшее пишется в журнал, но не считается.</returns>
    bool Farewell(string what, Action<T> call);

    /// <summary>Ручка к объекту, который отдал этот же хозяин: например, к полю, построенному вкладом.</summary>
    /// <typeparam name="TOther">Тип объекта.</typeparam>
    /// <param name="value">Объект.</param>
    /// <returns>Ручка на того же хозяина, отпускаемая вместе с этой.</returns>
    /// <remarks>
    /// Хозяин берётся у этой ручки, а не у сборки объекта: вклад вправе вернуть экземпляр класса из
    /// контракта модуля, и по сборке такой объект приписался бы модулю, а не тому, кто его отдал.
    /// </remarks>
    IStudioGuarded<TOther> Guard<TOther>(TOther value) where TOther : class;

    /// <summary>Ставит построенное хозяином на экран за барьер: упавшая раскладка не роняет окно.</summary>
    /// <param name="view">Контрол, построенный кодом хозяина.</param>
    /// <returns>Место для контрола: падение замера или раскладки заменяет его строкой о сбое и
    /// засчитывается хозяину.</returns>
    /// <remarks>
    /// Avalonia считает дерево окна целиком, и исключение из чужого замера унесло бы проход всего окна —
    /// со всеми открытыми документами. Панели расширений студия ставит за такой же барьер сама.
    /// </remarks>
    Control Host(Control view);
}

/// <summary>Вклад в контракт модуля: экземпляр класса расширения, который зовут через шов.</summary>
/// <typeparam name="T">Тип вклада.</typeparam>
public interface IStudioContribution<out T> : IStudioGuarded<T> where T : StudioContribution
{
    /// <summary>Вклад встроенного модуля, а не внешнего плагина.</summary>
    /// <remarks>Нужен при выборе среди равных: свою настройку плагин ставит поверх студийной.</remarks>
    bool IsBuiltIn { get; }

    /// <summary>Атрибуты класса вклада — без вызова его кода.</summary>
    /// <typeparam name="TAttribute">Тип атрибута.</typeparam>
    /// <returns>Атрибуты, включая унаследованные; пусто — у отпущенного вклада.</returns>
    /// <remarks>Так модуль читает, к чему вклад относится: редактор свойства — тип значения, раздел — тип цели.</remarks>
    IReadOnlyList<TAttribute> Attributes<TAttribute>() where TAttribute : Attribute;
}
