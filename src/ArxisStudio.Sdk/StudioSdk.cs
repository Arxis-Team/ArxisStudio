    /// не снято. С этой версии поверхность SDK, набора и иконок записана, и её сдвиг мимо номера
    /// ловит тест.
    /// </para>
    /// <para>
    /// 5.3 — тема обещает расширению шкалу расстояний (<c>AxSpace</c>,
    /// <c>AxGapFormRow</c>, направленные зазоры вроде
    /// <c>AxSpaceSnugTrailingThickness</c>) и значения, которые идут за
    /// плотностью интерфейса. Ресурс темы — такое же обещание, как метод
    /// контракта: плагин, назвавший <c>AxSpace</c>, в студии без шкалы получил
    /// бы не ошибку, а нулевой отступ и сломанную вёрстку. Младший номер: ни
    /// один ключ не снят. С этой же версией SDK везёт правила ARX0008–ARX0010,
    /// называющие ключ вместо числа.
    /// </para>
    /// <para>
    /// 5.2 — у команды в манифесте появились название (<c>title</c>) и сочетание
    /// клавиш (<c>key</c>). Младший номер: оба поля необязательны, и манифест,
    /// не знающий о них, читается как читался.
    /// </para>
    /// <para>
    /// 5.1 — панель называет, кому внутри неё достаётся каретка
    /// (<see cref="ToolWindow.FocusTarget"/>), и появилась служба
    /// <see cref="IStudioFocus"/>. Младший номер: оба обещания добавлены, ни
    /// одно не снято — панель, не знающая о них, работает как работала.
    /// </para>
    /// <para>
    /// 5.0 — снята служба находок (<c>IStudioProblems</c>) вместе с панелью «Проблемы», которая их
    /// показывала: о найденном расширение говорит журналом, и второй дороги для того же студия не
    /// держит. Старший номер, потому что обещание снято, а не добавлено: плагин, звавший службу,
    /// в этой студии её не получит.
    /// </para>
    /// <para>
    /// 4.2 — <see cref="IStudioContext.ProjectPath"/> стал живым: он отвечает на открытие и
    /// закрытие проекта, а не остаётся тем, чем был при подъёме плагина.
    /// </para>
    /// <para>
    /// 4.1 — добавлены теги манифеста (<c>tags</c>).
    /// </para>
    /// </remarks>
    public const string Version = "7.0";

    /// <summary>
    /// Довольна ли эта версия SDK тем, что просит плагин.
    /// </summary>
    /// <param name="required">Что объявлено в манифесте; пусто — «любая».</param>
    /// <returns><c>true</c>, если плагин можно поднимать.</returns>
    /// <remarks>
    /// Неразобранная строка считается подходящей: манифест пишет человек, и
    /// отказать ему из-за опечатки в номере значило бы не запустить рабочий
    /// плагин по ничтожному поводу. О самой опечатке скажет проверка манифеста.
    /// </remarks>
    public static bool Satisfies(string? required)
    {
        if (!TryParse(required, out var wanted))
            return true;

        TryParse(Version, out var have);

        // Сравниваем по старшему, а при равенстве — по младшему: плагин,
        // написанный под 1.0, работает в студии с 1.3, обратное неверно.
        return have.Major != wanted.Major
            ? have.Major > wanted.Major
            : have.Minor >= wanted.Minor;
    }

    private static bool TryParse(string? version, out (int Major, int Minor) parsed)
    {
        parsed = default;

        if (string.IsNullOrWhiteSpace(version))
            return false;

        var parts = version.Split('.', StringSplitOptions.RemoveEmptyEntries);

        if (parts.Length == 0 || !int.TryParse(parts[0], out var major))
            return false;

        var minor = parts.Length > 1 && int.TryParse(parts[1], out var found) ? found : 0;

        parsed = (major, minor);
        return true;
    }
}
