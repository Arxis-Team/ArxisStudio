namespace ArxisStudio.Sdk;

/// <summary>
/// Версия контракта, по которой студия и плагин узнают друг друга.
/// </summary>
/// <remarks>
/// Плагин объявляет в манифесте, какая версия ему нужна (<c>sdk.min</c>), и
/// студия сверяет её с этой — до того, как что-нибудь загрузит. Плагин, которому
/// нужен SDK новее, поднимать нельзя: он будет звать то, чего в этой студии
/// ещё нет, и падать не там, где ошибся автор, а там, куда он не заглядывал.
/// <para>
/// Старший номер меняется, когда контракт перестаёт быть совместимым:
/// убранный метод, изменившаяся сигнатура. Младший — когда в него что-то
/// добавили: плагин, написанный под 1.0, работает в студии с SDK 1.3, обратное
/// неверно.
/// </para>
/// </remarks>
public static class StudioSdk
{
    /// <summary>Версия контракта этой студии.</summary>
    /// <remarks>
    /// 7.0 — словарь расширения называется кодом языка: <c>lang/en.json</c>, <c>lang/ru.json</c>,
    /// <c>lang/de.json</c>. Прежних имён — <c>lang/strings.json</c> для языка автора и
    /// <c>lang/strings.&lt;код&gt;.json</c> для переводов — студия больше не читает, а запасным
    /// языком стал английский, тот же, что у неё самой. Старший номер, потому что обещание снято:
    /// плагин, собранный под 6.x, в этой студии поднимется и останется без текста — вместо
    /// подписей покажет ключи. Взамен форма словаря одна на студию, её расширения и шаблон
    /// перевода, и встроенный модуль переносится во внешний плагин вместе со строками.
    /// <para>
    /// 6.5 — значок сам берёт клетку под этот экран: <c>AxIcon.Cell</c> называет её шаблону, а
    /// <c>AxIcon.Shown</c> — путь, нарисованный в ней. Набор нарисован не в одной клетке, а в
    /// восьми: 12, 15, 16, 18, 20, 21, 24 и 28 — столько пикселей значок занимает на масштабах от
    /// 100 до 200 %. Прежде путь клетки 16 растягивался на любое число пикселей, и на дробных
    /// масштабах у штриха не оставалось ядра: доля пикселей, закрашенных целиком, падала с 54 % при
    /// 100 % до 28 % при 125 %, а у мелкого значка держалась на 1.3 % всегда. Младший номер:
    /// добавлены два свойства, снятого нет.
    /// </para>
    /// <para>
    /// 6.4 — поиск разбирает клавиатуру сам и говорит об этом событиями <c>Accepted</c> и
    /// <c>Cancelled</c>: стрелки водят выбор, Enter принимает, Esc бросает, щелчок по строке
    /// значит то же, что Enter. Рядом — <c>AxToolTip.Gesture</c>: жест команды, который подсказка
    /// показывает возле текста. Свойство наследуемое, потому что подсказку рисует отдельное окно,
    /// и своего жеста у него нет — как нет и своего контекста данных. Младший номер: добавлено,
    /// снятого нет.
    /// </para>
    /// <para>
    /// 6.3 — разделитель меряет себя сам: <c>AxDivider.Hairline</c> отдаёт один пиксель устройства
    /// в единицах раскладки при нынешнем масштабе окна, и той же мерой меряет свои границы движок
    /// докинга. Прибитая единица раскладки ровна пикселю только при 100 % и 200 %, а при 125 % и
    /// 150 % округляется до двух — линия, задуманная волосяной, становилась вдвое толще там, где
    /// всё остальное оставалось на месте. Младший номер: добавлен метод, снятого нет.
    /// </para>
    /// <para>
    /// 6.2 — у геометрии темы появились имена. Линия в пиксель — <c>AxHairline</c> и её толщины по
    /// сторонам, — плитка аватара и клетка, в которой нарисован набор, кольцо спиннера с его
    /// обводкой, дорожка хода и ползунка с радиусом в половину её высоты, ручка ползунка, полоса
    /// выбранной вкладки и точка несохранённых правок, бейдж, чип клавиши, наименьшая высота
    /// многострочного поля, ширины всплывающих поверхностей и пределы меню, половины кнопки с
    /// раздельным действием, кольцо выбранной радиокнопки, разрядка заголовка секции, рамка
    /// подсказки докинга и ширины экранов самой студии. Числа эти стояли в шаблонах и разметке, и
    /// «рамка в пиксель» была не решением, а совпадением сорока мест. Младший номер: ключи
    /// добавлены, ни один не снят.
    /// </para>
    /// <para>
    /// 6.1 — тема обещает расширению высоты хрома и шаг лестницы дерева: <c>AxTabHeight</c>
    /// (вкладка и шапка панели), <c>AxTitleBarHeight</c>, <c>AxStatusBarHeight</c>,
    /// <c>AxMenuRowHeight</c>, <c>AxToolbarButtonSize</c>, <c>AxWindowButtonWidth</c> и
    /// <c>AxTreeIndent</c>. Все семь идут за плотностью интерфейса, и панель плагина, назвавшая
    /// их, следует за ней вместе со студией — прежде эти числа стояли в шаблонах студии и не
    /// двигались вовсе. Вместе с ними обещана доля, которой мерится высота строки абзаца
    /// (<c>AxLineHeightRatio</c>), и присоединённое свойство набора
    /// <c>AxText.LineHeightRatio</c>: интервал долей кегля, а не пикселями, — пиксельная высота
    /// строки не выросла бы с настройкой размера текста. Младший номер: ни один ключ и ни один
    /// член не сняты. Значения при этом сдвинулись: кегли шкалы стали целыми (12 и 11 вместо
    /// 11,5 и 10,5), <c>AxFontSizeLarge</c> из заголовка диалога стал крупным кеглем экрана
    /// (20 вместо 14), а высоты и отступы легли на сетку четырёх.
    /// </para>
    /// <para>
    /// 6.0 — палитра темы называет роль, а не место в ряду: <c>AxBg2</c> стал <c>AxSurfacePanel</c>,
    /// <c>AxFg3</c> — <c>AxTextTertiary</c>, <c>AxBrd</c> — <c>AxStrokeSubtle</c>, а ступеней шкал
    /// (<c>AxGray1</c>, <c>AxBlue6</c>) в словаре больше нет. Значения не сдвинулись ни на пиксель, но
    /// ключ темы — обещание расширению с 5.3, и разметка, назвавшая прежний, получает в этой студии
    /// не ошибку, а пустую кисть. Старший номер, потому что обещание снято: плагин, собранный под 5.x,
    /// поднимется, но цвета темы у него не разрешатся. Прежние имена при сборке называет
    /// <c>ARX0009</c> — в разметке и в коде, вместе с ролью, которая их заменила.
    /// </para>
    /// <para>
    /// Тем же номером разрезан набор контролов и иконок. Вид контрола — свойство, а не класс
    /// стиля: <c>AxButton.Appearance</c> и <c>Size</c>, новый <c>AxToggleButton</c>, роль и тон
    /// текста <c>AxText.Role</c> и <c>AxText.Tone</c>, <c>AxValidation.State</c> у полей,
    /// <c>AxChip.Kind</c>, <c>AxAvatar.Shape</c> и <c>Tint</c>, <c>AxSpinner.Size</c>,
    /// <c>AxMenuItem.IsDestructive</c>, <c>AxTabStrip.Kind</c>, <c>AxIcon.Size</c>; классов вида
    /// тема не знает, и класс с опечаткой больше не даёт молча контрол по умолчанию. Сняты
    /// <c>AxNotificationCard</c>, <c>AxTeachingTip</c> и хлебные крошки — у них не было ни одного
    /// потребителя, — глифы палитры дизайнера <c>AxIcons.Toolbox</c> и публичные
    /// преобразователи шаблонов со своими числами. Значок строки дерева — путь, как у вкладки;
    /// разделитель рисует себя сам и красится <c>Fill</c>. Поверхность записана один раз:
    /// дальше набор только растёт младшими номерами.
    /// </para>
    /// <para>
    /// 5.5 — у панели и у команды в манифесте появился значок (<c>icon</c>), той же записью, что у
    /// кнопки полосы: имя из набора студии или контур в сетке 16. Значок панели стоит на её вкладке,
    /// значок команды — у пункта меню, в строке палитры и на кнопке полосы, не назвавшей своего.
    /// Младший номер: поле необязательно, и манифест, не знающий о нём, читается как читался.
    /// </para>
    /// <para>
    /// 5.4 — добавки в набор контролов, который плагин видит общим: поправка места меню на поле под
    /// тень (<c>AxMenuFlyout.Compensation</c>, ключ <c>AxPopupShadowRoom</c>), высота строки блока
    /// кода долей кегля (<c>AxCodeBlock.LineHeightRatio</c>) и подсказка с полным текстом сокращённой
    /// подписи (<c>AxTrimmedTip</c>). Набор — единственная сознательная часть контракта вне SDK:
    /// плагин строит интерфейс на нём и собирается против его типов, и добавка туда — такое же
