using Avalonia.Threading;

namespace ArxisStudio.Modules.Console.Feed;

/// <summary>
/// Одно перестроение списка на кадр, сколько бы записей ни пришло.
/// </summary>
/// <remarks>
/// Журнал зовёт своё событие на каждую запись, и писать в него могут пачкой:
/// плагин в цикле, каскад перезагрузки, разбор языковых пакетов при старте.
/// Перестраивать список на каждую значило бы тратить кадр на работу, итог
/// которой человек не увидит, — он увидит только последнюю.
/// <para>
/// Та же мысль, что у отложенной записи раскладки в <c>StudioDock</c>: правок
/// много и они частые, а нужен от них один итог.
/// </para>
/// <para>
/// Просить можно из любого потока — журнал студии потокобезопасен, но не
/// привязан к потоку интерфейса, и запись из фоновой задачи плагина приходит
/// из пула. Перестроение при этом всегда происходит в потоке интерфейса:
/// список, который читает Avalonia, править больше неоткуда.
/// </para>
/// </remarks>
public sealed class Refresh
{
    private readonly Lock _gate = new();
    private readonly Action _rebuild;

    private bool _scheduled;
    private bool _stopped;

    /// <summary>Заводит склейку над перестроением.</summary>
    /// <param name="rebuild">Что делать, когда придёт срок; зовётся в потоке интерфейса.</param>
    public Refresh(Action rebuild)
    {
        ArgumentNullException.ThrowIfNull(rebuild);

        _rebuild = rebuild;
    }

    /// <summary>
    /// Сколько раз перестроение действительно случилось.
    /// </summary>
    /// <remarks>
    /// Открыто ради теста, и это честнее скрытого поля: «пачка из пятисот
    /// записей перестроила список один раз» — утверждение о поведении, и
    /// проверять его надо счётом, а не глядя на секундомер.
    /// </remarks>
    public int Runs { get; private set; }

    /// <summary>
    /// Просит перестроить список; несколько просьб подряд дадут одно
    /// перестроение.
    /// </summary>
    /// <remarks>
    /// Приоритет фоновый: ниже отрисовки и ввода. Под нагрузкой диспетчер сам
    /// расширяет окно склейки, а в безголовом режиме очередь сливает
    /// <c>Dispatcher.UIThread.RunJobs()</c> — таймер здесь не годится, в
    /// тестах время стоит.
    /// </remarks>
    public void Ask()
    {
        lock (_gate)
        {
            if (_stopped || _scheduled)
                return;

            _scheduled = true;
        }

        Dispatcher.UIThread.Post(Run, DispatcherPriority.Background);
    }

    /// <summary>
    /// Перестраивает немедленно, в текущем потоке.
    /// </summary>
    /// <remarks>
    /// Нужно ровно один раз — когда панель строится и обязана показать то, что
    /// в журнале уже есть. Отложить первое наполнение значило бы показать
    /// человеку пустую панель и заполнить её через кадр.
    /// </remarks>
    public void Now()
    {
        lock (_gate)
        {
            if (_stopped)
                return;
        }

        Runs++;
        _rebuild();
    }

    /// <summary>
    /// Панель уходит: назначенное перестроение больше не состоится.
    /// </summary>
    /// <remarks>
    /// Просьба могла уже лечь в очередь диспетчера, и отозвать её оттуда
    /// нечем. Значит, отвечать должен сам обработчик — иначе он тронул бы
    /// список панели, которую студия уже отпустила.
    /// </remarks>
    public void Stop()
    {
        lock (_gate)
        {
            _stopped = true;
        }
    }

    private void Run()
    {
        lock (_gate)
        {
            _scheduled = false;

            if (_stopped)
                return;
        }

        Runs++;
        _rebuild();
    }
}
