using Avalonia.Media;

namespace ArxisStudio.Settings;

/// <summary>
/// Страница окна настроек — узел дерева слева и то, что показано справа.
/// </summary>
/// <remarks>
/// Окно знает только этот интерфейс. Сегодня его реализуют две страницы самой
/// студии: оформление и настройки одного расширения, собранные по манифесту.
/// <para>
/// Когда у плагина появится право писать <b>свою</b> страницу, добавится третья
/// реализация — переходник, который завернёт контрол плагина в
/// <c>PluginSurface</c> и проведёт <see cref="Commit"/> с <see cref="Revert"/>
/// через <c>PluginGuard</c>: чужой код зовут через шов, а не мимо него. Ни
/// окно, ни дерево, ни правило «Сохранить/Отмена» при этом не меняются — и
/// ради этого интерфейс здесь, а не набор полей внутри окна.
/// </para>
/// <para>
/// Содержимого страница не строит: чем её рисовать, решает разметка окна по
/// типу страницы. Так вёрстка остаётся в разметке, а не расползается по
/// моделям — и правило «интерфейс строится на <c>Ax*</c>» проверяется
/// анализатором ARX0006 там, где ему и место.
/// </para>
/// </remarks>
public interface ISettingsPage
{
    /// <summary>Имя страницы для поиска и для памяти о выбранной.</summary>
    string Id { get; }

    /// <summary>Подпись в дереве.</summary>
    string Title { get; }

    /// <summary>Значок в дереве; null — без значка.</summary>
    Geometry? Icon { get; }

    /// <summary>Вложенные страницы; пусто — узел без детей.</summary>
    IReadOnlyList<ISettingsPage> Children { get; }

    /// <summary>
    /// По чему страницу находит поиск.
    /// </summary>
    /// <remarks>
    /// Подпись, метки строк и ключи: ключ человек видит в файле настроек и
    /// ищет именно его, когда пришёл из документации соседа.
    /// </remarks>
    IEnumerable<string> Terms { get; }

    /// <summary>На странице есть несохранённое.</summary>
    bool HasChanges { get; }

    /// <summary>
    /// Отдаёт накопленное хранилищу.
    /// </summary>
    /// <param name="problems">Куда сложить причины, если записать не вышло.</param>
    /// <remarks>
    /// Страница пишет столько, сколько может, и о непрошедшем говорит через
    /// список: половина настроек, записанная молча, хуже отказа целиком —
    /// человек ушёл бы, считая сохранённым и то, что не легло.
    /// <para>
    /// Задачей, потому что записать — не всегда значит записать файл: страница
    /// плагинов по «Сохранить» опускает выключенных и поднимает включённых, а
    /// выгрузка кооперативная и ждёт до пяти секунд. Синхронное сохранение
    /// либо соврало бы о применённом, либо заморозило бы поток интерфейса.
    /// </para>
    /// </remarks>
    Task CommitAsync(ICollection<string> problems);

    /// <summary>Забывает накопленное и возвращает то, что было при открытии.</summary>
    void Revert();
}
