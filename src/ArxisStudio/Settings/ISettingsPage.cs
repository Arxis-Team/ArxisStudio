using Avalonia.Media;

namespace ArxisStudio.Settings;

/// <summary>
/// Страница окна настроек — узел дерева слева и то, что показано справа.
/// </summary>
/// <remarks>
/// Окно знает только этот интерфейс. Сегодня его реализуют страницы самой студии:
/// оформление, клавиши, плагины, ветка расширений и настройки одного расширения,
/// собранные по манифесту.
/// <para>
/// Когда у плагина появится право писать <b>свою</b> страницу, добавится ещё одна
/// реализация — переходник, который завернёт контрол плагина в
/// <c>PluginSurface</c> и проведёт <see cref="CommitAsync(ICollection{string})"/> с <see cref="Revert"/>
/// через <c>PluginGuard</c>: чужой код зовут через шов, а не мимо него. Ни
/// окно, ни дерево, ни правило «Сохранить/Отмена» при этом не меняются — и
/// ради этого интерфейс здесь, а не набор полей внутри окна.
/// </para>
/// <para>
/// Содержимого страница не строит: чем её рисовать, решает разметка окна по
/// типу страницы. Так вёрстка остаётся в разметке, а не расползается по
/// моделям — и правило «интерфейс строится на <c>Ax*</c>» проверяется
/// анализатором ARX0006 там, где ему и место.
/// </para>
/// </remarks>
public interface ISettingsPage
{
    /// <summary>Имя страницы для поиска и для памяти о выбранной.</summary>
    string Id { get; }

    /// <summary>Подпись в дереве.</summary>
    string Title { get; }

    /// <summary>Значок в дереве; null — без значка.</summary>
    Geometry? Icon { get; }

    /// <summary>Вложенные страницы; пусто — узел без детей.</summary>
    IReadOnlyList<ISettingsPage> Children { get; }

    /// <summary>
    /// По чему страницу находит поиск.
    /// </summary>
    /// <remarks>
    /// Подпись, метки строк и ключи: ключ человек видит в файле настроек и
    /// ищет именно его, когда пришёл из документации соседа.
    /// </remarks>
    IEnumerable<string> Terms { get; }

    /// <summary>На странице есть несохранённое.</summary>
    bool HasChanges { get; }

    /// <summary>
    /// <see cref="HasChanges"/> мог смениться.
    /// </summary>
    /// <remarks>
    /// Окно отмечает правленый раздел точкой в дереве и показывает «Сбросить» в шапке, пока
    /// правка не сохранена, — как Rider. Спрашивать страницу на каждый кадр нечем, а правят её
    /// строки, о которых окно не знает: сказать, что пора посмотреть заново, может только она.
    /// </remarks>
    event EventHandler? Changed;

    /// <summary>
    /// Сужает показ строк страницы по запросу поиска.
    /// </summary>
    /// <param name="query">Что ищут; <c>null</c> — показать все строки.</param>
    /// <remarks>
    /// Правило то же, что у дерева, только уровнем ниже: страница, совпавшая сама, показывает все
    /// строки — человек искал её целиком, — а уцелевшая ради строк показывает только совпавшие.
    /// Решает, какая из двух, окно: оно знает и подпись страницы, и её предков. Страница без строк
    /// оставляет вызов без ответа.
    /// </remarks>
    void Narrow(string? query);

    /// <summary>
    /// Отдаёт накопленное хранилищу.
    /// </summary>
    /// <param name="problems">Куда сложить причины, если записать не вышло.</param>
    /// <remarks>
    /// Страница пишет столько, сколько может, и о непрошедшем говорит через
    /// список: половина настроек, записанная молча, хуже отказа целиком —
    /// человек ушёл бы, считая сохранённым и то, что не легло.
    /// <para>
    /// Задачей, потому что записать — не всегда значит записать файл: страница
    /// плагинов по «Сохранить» опускает выключенных и поднимает включённых, а
    /// выгрузка кооперативная и ждёт до пяти секунд. Синхронное сохранение
    /// либо соврало бы о применённом, либо заморозило бы поток интерфейса.
    /// </para>
    /// </remarks>
    Task CommitAsync(ICollection<string> problems);

    /// <summary>
    /// Отдаёт накопленное хранилищу — вживую или только на диск.
    /// </summary>
    /// <param name="problems">Куда сложить причины, если записать не вышло.</param>
    /// <param name="live">
    /// Применить к работающей студии; <c>false</c> — только записать: студия сейчас перезапустится
    /// и прочтёт записанное сама.
    /// </param>
    /// <remarks>
    /// Разница есть не у всякой страницы, и по умолчанию её нет: записать настройку и применить её —
    /// одно и то же для оформления и расширений. Отличается страница плагинов: применить там значит
    /// опустить и поднять плагины, а перед перезапуском это работа впустую.
    /// </remarks>
    Task CommitAsync(ICollection<string> problems, bool live) => CommitAsync(problems);

    /// <summary>Забывает накопленное и возвращает то, что было при открытии.</summary>
    void Revert();
}
