using Xunit;

namespace ArxisStudio.Tests;

/// <summary>
/// Тесты, которые трогают общее на весь процесс, идут по одному.
/// </summary>
/// <remarks>
/// Общего два. Первое — словарь строк: <c>Localizer</c> один на процесс, и
/// тест, переключивший язык или подменивший папку словарей, менял бы текст
/// под руками у соседа. Второе — выгрузка контекстов загрузки: проверка
/// «прежний контекст действительно умер» опирается на сборщик мусора, а он
/// в процессе тоже один; пока рядом поднимают и выгружают плагины другие
/// классы, ответ у неё плавает.
/// <para>
/// xUnit по умолчанию пускает классы параллельно, и это правильно для
/// остальных: очередь здесь заведена ровно для тех, у кого общее состояние,
/// а не на весь набор.
/// </para>
/// </remarks>
[CollectionDefinition(Name)]
public sealed class StudioStateCollection
{
    /// <summary>Имя коллекции.</summary>
    public const string Name = "StudioState";
}
