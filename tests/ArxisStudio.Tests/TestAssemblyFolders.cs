using System.Runtime.CompilerServices;
using ArxisStudio.Services;

namespace ArxisStudio.Tests;

/// <summary>
/// Дорога процесса тестов к папкам модулей.
/// </summary>
/// <remarks>
/// Тесты собираются в ту же раскладку, что и студия: у каждого модуля своя папка под
/// <c>modules</c>, а не место рядом с тестовой сборкой. Плоский выход делил бы одну папку и один
/// <c>module.json</c> на четыре модуля — то есть проверялась бы раскладка, которой у продукта нет,
/// а ради неё пришлось бы завести второе правило поиска манифеста, живущее только в тестах.
/// <para>
/// Дорогу показывает инициализатор модуля сборки: среда зовёт его прежде, чем тронет любой член
/// этой сборки, — то есть раньше, чем обнаружение тестов доберётся до типов, которые тянут сборки
/// модулей. Правило то же, что у <c>Program.Main</c> студии, и по той же причине: сам инициализатор
/// не называет ни одного типа из <c>modules</c>, иначе JIT разрешал бы их до того, как встанет
/// резолвер.
/// </para>
/// <para>
/// Платформа не подключается: в выходе тестов её папки нет вовсе — всё, на чём стоит студия, лежит
/// рядом с тестовой сборкой обычным порядком ссылок.
/// </para>
/// </remarks>
internal static class TestAssemblyFolders
{
    /// <summary>Показывает основному контексту загрузки папки модулей.</summary>
    [ModuleInitializer]
    internal static void Attach() => StudioAssemblyFolder.Modules.Attach();
}
